import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
const root = path.resolve(process.argv[2] || '.');
const require = createRequire(path.join(process.argv[3] || root, 'package.json'));
const { PGlite } = require('@electric-sql/pglite');
const db = new PGlite();
await db.exec(`
create role anon; create role authenticated; create role service_role;
create schema auth; create schema storage; create schema extensions;
create table auth.users(id uuid primary key, raw_user_meta_data jsonb default '{}');
create function auth.uid() returns uuid language sql as $$select nullif(current_setting('test.uid', true), '')::uuid$$;
create function auth.jwt() returns jsonb language sql as $$select '{}'::jsonb$$;
create function extensions.digest(text,text) returns bytea language sql as $$select sha256(convert_to($1,'UTF8'))$$;
create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
create table storage.objects(id uuid primary key,bucket_id text,name text);
create function storage.foldername(text) returns text[] language sql as $$select string_to_array($1,'/')$$;
alter default privileges in schema public grant execute on functions to anon, authenticated;
alter default privileges in schema public grant all on tables to anon, authenticated;
grant usage on schema public, auth to anon, authenticated, service_role;
`);
for (const file of ['001_core.sql','002_invitation_profiles.sql','003_invitation_security.sql','004_atomic_approval.sql','005_atomic_synthesis.sql','006_conversation_access.sql','007_function_permissions.sql','008_ai_budget.sql','009_work_routing.sql','010_beta_admin.sql','011_gemini36_budget.sql','012_ai_review_lifecycle.sql','013_evidence_privacy.sql']) {
  await db.exec(readFileSync(path.join(root,'supabase/migrations',file),'utf8').replace('create extension if not exists pgcrypto;',''));
}
await db.exec(readFileSync(path.join(root,'supabase/migrations/012_ai_review_lifecycle.sql'),'utf8'));
await db.exec(readFileSync(path.join(root,'supabase/migrations/013_evidence_privacy.sql'),'utf8'));
const id = n => `00000000-0000-4000-8000-${String(n).padStart(12,'0')}`;
const [owner,employee,stranger,org,mission,assignment,conversation,message] = Array.from({length:8},(_,i)=>id(i+1));
await db.exec(`
insert into auth.users(id) values ('${owner}'),('${employee}'),('${stranger}');
insert into organisations(id,name,slug,created_by) values ('${org}','Company','company','${owner}');
insert into organisation_memberships(organisation_id,user_id,role) values ('${org}','${owner}','owner'),('${org}','${employee}','participant');
insert into missions(id,organisation_id,title,objective,created_by,status) values ('${mission}','${org}','Review','Review process','${owner}','active');
insert into mission_assignments(id,organisation_id,mission_id,user_id) values ('${assignment}','${org}','${mission}','${employee}');
set role authenticated; set test.uid='${employee}';
insert into conversations(id,assignment_id,mission_id,user_id) values ('${conversation}','${assignment}','${mission}','${employee}');
insert into messages(id,conversation_id,sender,content,confidentiality) values ('${message}','${conversation}','participant','A private process detail','PRIVATE');
`);
const observation = {category:'process',summary:'Process detail',detail:'Only my review',confidence:0.8,sourceConfidentiality:'PRIVATE'};
const draft = (ids=[message], observations=[observation]) => db.query('select save_conversation_draft($1,$2,$3,$4) as result',[assignment,ids,'Review summary',JSON.stringify(observations)]);
const approve = review => db.query('select approve_conversation_review($1,$2)',[assignment,review]);
await assert.rejects(db.query("update mission_assignments set status='completed' where id=$1",[assignment]));
await assert.rejects(db.query('select approve_conversation($1)',[assignment]));
await assert.rejects(draft([]));
await assert.rejects(draft([message],[{...observation,sourceConfidentiality:'SHARE'}]));
const first = (await draft()).rows[0].result.review_id;
await assert.rejects(draft([message],[{...observation,confidence:2}]));
assert.equal((await db.query('select id from conversation_summaries')).rows[0].id,first,'Failed replacement preserves draft');
await assert.rejects(db.query("update conversation_summaries set status='approved'"));
await assert.rejects(db.query('delete from observations'));
await db.exec(`set test.uid='${stranger}'`);
await assert.rejects(draft()); await assert.rejects(approve(first));
await db.exec(`set test.uid='${employee}'`);
const nextMessage = id(9);
await db.query("insert into messages(id,conversation_id,sender,content,confidentiality) values ($1,$2,'participant','One further detail','SHARE')",[nextMessage,conversation]);
assert.equal((await db.query('select * from conversation_summaries')).rows.length,0);
await assert.rejects(approve(first));
await assert.rejects(draft());
const current = (await draft([message,nextMessage],[observation,{...observation,sourceConfidentiality:'SHARE'}])).rows[0].result.review_id;
await assert.rejects(approve(first));
await db.exec(`reset role; create function fail_approval_audit() returns trigger language plpgsql as $$begin raise exception 'injected audit failure'; end$$;
create trigger fail_approval_audit before insert on audit_events for each row execute function fail_approval_audit();
set role authenticated; set test.uid='${employee}';`);
await assert.rejects(approve(current));
assert.equal((await db.query('select status from conversation_summaries')).rows[0].status,'draft');
assert.equal((await db.query('select participant_approved from observations')).rows[0].participant_approved,false);
await db.exec('reset role; drop trigger fail_approval_audit on audit_events; set role authenticated;');
await approve(current); await approve(current);
assert.equal((await db.query('select status from mission_assignments')).rows[0].status,'completed');
await assert.rejects(draft([message,nextMessage]));
await assert.rejects(db.query("insert into messages(conversation_id,sender,content,confidentiality) values ($1,'participant','Too late','SHARE')",[conversation]));
await assert.rejects(db.query("update mission_assignments set status='in_progress', completed_at=null where id=$1",[assignment]));
await db.exec(`set test.uid='${owner}'`);
assert.equal((await db.query('select * from observations')).rows.length,1,'Manager sees approved SHARE, not PRIVATE');
const written = (await db.query('select assign_mission_participant($1,$2) as id',[mission,owner])).rows[0].id;
await db.query('select submit_written_response($1,$2,$3,$4)',[written,'Written feedback','This response remains functional without AI.','SHARE']);
await db.query('select submit_written_response($1,$2,$3,$4)',[written,'Duplicate','Do not replace the original submitted response.','SHARE']);
assert.equal((await db.query('select status from mission_assignments where id=$1',[written])).rows[0].status,'completed');
await db.exec(`reset role;
insert into observations(organisation_id,mission_id,conversation_id,user_id,category,summary,detail,confidentiality,participant_approved,confidence)
values ('${org}','${mission}','${conversation}','${employee}','process','Contributed detail','No account attribution','CONTRIBUTE',true,0.8);
insert into source_records(organisation_id,user_id,source_type,title,confidentiality) values ('${org}',null,'file','Private imported record','PRIVATE'),('${org}','${employee}','file','Private employee upload','PRIVATE');
set role authenticated; set test.uid='${owner}';`);
