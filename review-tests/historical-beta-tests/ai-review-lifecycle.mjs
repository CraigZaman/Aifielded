assert.equal(contributed.user_id,null);
assert.ok(!('conversation_id' in contributed));
assert.equal((await db.query("select * from observations where confidentiality='CONTRIBUTE'")).rows.length,0);
assert.equal((await db.query('select count_evidence_contributors($1) as count',[[contributed.id]])).rows[0].count,1);
assert.equal((await db.query('select * from source_records')).rows.length,0,'Even unattributed private source records stay private');
await db.exec(`set test.uid='${stranger}'`);
assert.equal((await db.query('select * from management_observations')).rows.length,0);
await assert.rejects(db.query('select count_evidence_contributors($1)',[[contributed.id]]));
await db.exec('set role anon');
await assert.rejects(db.query('select * from management_observations'));
await db.exec(`reset role; update organisation_memberships set status='suspended' where user_id='${employee}'; set role authenticated; set test.uid='${employee}'`);
await assert.rejects(approve(current));
await db.exec('reset role');
for (const signature of ['save_conversation_draft(uuid,uuid[],text,jsonb)','approve_conversation_review(uuid,uuid)']) {
  assert.equal((await db.query("select has_function_privilege('anon',$1,'EXECUTE') as allowed",[`public.${signature}`])).rows[0].allowed,false);
}
await db.close();
