import { PGlite } from '@electric-sql/pglite';
import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
const db = new PGlite();
const user='20000000-0000-0000-0000-000000000001';
const assignment='30000000-0000-0000-0000-000000000001';
await db.exec(`
create role authenticated;
create schema auth;
create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('test.uid',true),'')::uuid $$;
create function public.is_workspace_member(uuid) returns boolean language sql stable as $$ select true $$;
create table mission_assignments(id uuid primary key,user_id uuid,organisation_id uuid,status text,completed_at timestamptz);
create table conversations(id uuid primary key,assignment_id uuid,user_id uuid,completed_at timestamptz);
create table conversation_summaries(id uuid primary key,conversation_id uuid,user_id uuid,status text,approved_at timestamptz,updated_at timestamptz);
create table observations(conversation_id uuid,user_id uuid,participant_approved boolean,organisation_id uuid,confidentiality text);
grant usage on schema auth,public to authenticated;
grant all on all tables in schema public to authenticated;
insert into mission_assignments values('${assignment}','${user}','${assignment}','in_progress',null);
insert into conversations values('${assignment}','${assignment}','${user}',null);
insert into conversation_summaries values('${assignment}','${assignment}','${user}','draft',null,null);
insert into observations values('${assignment}','${user}',false,null,'PRIVATE');
create function fail_completion() returns trigger language plpgsql as $$ begin raise exception 'injected failure'; end $$;
create trigger fail_completion before update on conversations for each row execute function fail_completion();
`);
await db.exec(readFileSync(process.argv[2],'utf8'));
await db.query(`select set_config('test.uid',$1,false)`,[user]);
await db.exec('set role authenticated');
await assert.rejects(db.query(`select approve_conversation($1)`,[assignment]),/injected failure/);
assert.equal((await db.query('select status from conversation_summaries')).rows[0].status,'draft');
assert.equal((await db.query('select participant_approved from observations')).rows[0].participant_approved,false);
assert.equal((await db.query('select status from mission_assignments')).rows[0].status,'in_progress');
await db.exec('reset role; drop trigger fail_completion on conversations; set role authenticated;');
await db.query(`select approve_conversation($1)`,[assignment]);
assert.equal((await db.query('select status from conversation_summaries')).rows[0].status,'approved');
assert.equal((await db.query('select status from mission_assignments')).rows[0].status,'completed');
assert.equal((await db.query('select confidentiality from observations')).rows[0].confidentiality,'PRIVATE');
await db.query(`select approve_conversation($1)`,[assignment]);
await db.query(`select set_config('test.uid',$1,false)`,['20000000-0000-0000-0000-000000000002']);
await assert.rejects(db.query(`select approve_conversation($1)`,[assignment]),/Conversation not available/);
await db.close();
console.log('PASS: approval rollback, successful completion, confidentiality preservation, retry and foreign-user rejection');
